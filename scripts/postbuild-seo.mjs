#!/usr/bin/env node
/**
 * @license MIT
 * ============================================================================
 * scripts/postbuild-seo.mjs — Post-Export Sitemap, 404, IndexNow & Safety Gate
 * ============================================================================
 * Plain-English Overview (Read-Along Guide):
 *   - LINE 1 (`#!/usr/bin/env node`): Called a Unix "shebang." It tells macOS
 *     and Linux terminals: "If someone runs this script directly, execute it
 *     using the `node` (Node.js) JavaScript runtime."
 *   - WHEN THIS FILE RUNS: Build-time only (Node.js). In `package.json`, npm
 *     has a built-in lifecycle convention: naming a script `"postbuild"` makes
 *     `npm run build` automatically run this file immediately AFTER `next build`
 *     finishes exporting static HTML files into the `out/` folder.
 *   - WHAT DATA FEEDS INTO IT: Every pre-rendered `.html` file generated by
 *     Next.js inside `/out`.
 *   - WHAT OUTPUT IT PRODUCES:
 *     1. Guarantees `out/404.html` exists and carries `<meta name="robots" content="noindex, follow">`
 *        so Nginx can serve genuine HTTP 404 responses that never pollute Google.
 *     2. Writes `robots.txt` (welcoming search crawlers and pointing them to our
 *        sitemap) and our IndexNow verification key `.txt` file (for instant
 *        Bing/IndexNow indexing).
 *     3. Walks `out/` recursively to discover every canonical pre-rendered route
 *        and writes `out/sitemap.xml` (mirrored to `public/sitemap.xml`).
 *     4. Performs a final HTML Safety Gate across 100% of exported `.html` files
 *        so zero forbidden real-world campus names, personal trauma triggers, or
 *        technical engineering jargon can ever reach production (`exit code 1`
 *        aborts the build immediately if any rule is violated).
 * ============================================================================
 */

// Node.js built-in standard library imports (prefixed with `node:` so it is
// unmistakable that these come from Node.js itself rather than `node_modules`):
// - `fs` ("File System"): reads, copies, and writes files/folders on disk.
// - `path`: safely glues folder and file names together across macOS/Linux/Windows.
// - `fileURLToPath`: converts ES Module `import.meta.url` (`file:///...`) into a normal path.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// In classic Node CommonJS scripts, `__filename` and `__dirname` existed automatically.
// In modern ES Modules (`.mjs`), we derive them explicitly from `import.meta.url`:
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// `path.resolve(__dirname, "..")` steps one folder UP from `scripts/` to the
// project root (`subdomains/lore/`).
const LORE_ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(LORE_ROOT, "out");
const PUBLIC_DIR = path.join(LORE_ROOT, "public");
const ORIGIN = "https://lore.raggiesoft.com";
const INDEXNOW_KEY = "726167676965736f6674696e6465786e";

// `new Date().toISOString()` returns a timestamp like `"2026-11-20T05:33:03.000Z"`.
// `.slice(0, 10)` grabs just the first 10 characters (`"YYYY-MM-DD"`) for XML `<lastmod>`.
const TODAY = new Date().toISOString().slice(0, 10);

// Guard clause: if `out/` doesn't exist (e.g., someone ran postbuild before `next build`),
// print an error to `stderr` (`console.error`) and stop immediately with a non-zero
// exit code (`1` = failure in Unix/CI pipelines; `0` = success).
if (!fs.existsSync(OUT_DIR)) {
  console.error(`❌ [postbuild-seo] Missing Next.js static export directory: ${OUT_DIR}`);
  process.exit(1);
}

// ----------------------------------------------------------------------------
// 1. Ensure genuine static `out/404.html` with `noindex, follow`
// ----------------------------------------------------------------------------
// Different Next.js versions/configurations may emit `src/app/not-found.tsx` at
// slightly different paths inside `out/`. We check all candidate locations and
// ensure Nginx always finds a top-level `out/404.html` file.
const out404 = path.join(OUT_DIR, "404.html");
const candidates404 = [
  out404,
  path.join(OUT_DIR, "404", "index.html"),
  path.join(OUT_DIR, "_not-found.html"),
  path.join(OUT_DIR, "_not-found", "index.html"),
];

if (!fs.existsSync(out404)) {
  // `Array.prototype.find()` returns the FIRST item in the array where the test
  // callback returns `true` (or `undefined` if none match).
  const found = candidates404.find((p) => fs.existsSync(p));
  if (found) {
    fs.copyFileSync(found, out404);
  }
}

if (!fs.existsSync(out404)) {
  console.error("❌ [postbuild-seo] Could not locate exported 404 page in out/.");
  process.exit(1);
}

// Read the exported 404 HTML as a UTF-8 text string and verify it includes a
// `noindex` robots meta tag:
// - `noindex`: tells Google/Bing NOT to list the 404 error page in search results.
// - `follow`: tells crawlers they CAN follow the helpful recovery links on the page.
let html404 = fs.readFileSync(out404, "utf8");
if (!/noindex/i.test(html404)) {
  html404 = html404.replace(
    /<head>/i,
    '<head><meta name="robots" content="noindex, follow"/>'
  );
  fs.writeFileSync(out404, html404, "utf8");
}

// ----------------------------------------------------------------------------
// 2. Ensure `robots.txt` and IndexNow key file exist in `public/` and `out/`
// ----------------------------------------------------------------------------
// Build `robots.txt` by joining an array of lines with newline characters (`"\n"`).
// `User-agent: *` + `Allow: /` welcomes all search crawlers and points them to `sitemap.xml`.
const robotsContent = [
  "User-agent: *",
  "Allow: /",
  "",
  `Sitemap: ${ORIGIN}/sitemap.xml`,
  "",
].join("\n");

// `{ recursive: true }` acts like `mkdir -p`: it creates `public/` if missing,
// and quietly succeeds without error if `public/` already exists.
fs.mkdirSync(PUBLIC_DIR, { recursive: true });
fs.writeFileSync(path.join(PUBLIC_DIR, "robots.txt"), robotsContent, "utf8");
fs.writeFileSync(path.join(OUT_DIR, "robots.txt"), robotsContent, "utf8");

// IndexNow is a protocol used by Bing, DuckDuckGo, and partner search engines:
// hosting `<KEY>.txt` at the root proves domain ownership for instant URL pinging.
fs.writeFileSync(path.join(PUBLIC_DIR, `${INDEXNOW_KEY}.txt`), `${INDEXNOW_KEY}\n`, "utf8");
fs.writeFileSync(path.join(OUT_DIR, `${INDEXNOW_KEY}.txt`), `${INDEXNOW_KEY}\n`, "utf8");

// ----------------------------------------------------------------------------
// 3. Walk `out/` for canonical HTML routes & audit exported HTML
// ----------------------------------------------------------------------------
/**
 * Recursively collects every `.html` file inside `dir` (and all its subfolders).
 * "Recursion" means a function calls ITSELF on each child subfolder until the
 * entire directory tree has been explored. We skip `_next/` because that folder
 * only holds compiled JS/CSS/font bundles, never canonical HTML pages.
 */
function walkHtmlFiles(dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "_next") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      // Spread (`...`) merges the child folder's `.html` paths into `results`.
      results.push(...walkHtmlFiles(full));
    } else if (entry.isFile() && entry.name.endsWith(".html")) {
      results.push(full);
    }
  }
  return results;
}

const htmlFiles = walkHtmlFiles(OUT_DIR);

// A JavaScript `Set` is a collection that automatically prevents duplicate values.
// Even if both `bands.html` and `bands/index.html` existed, `routeSet.add("/bands")`
// stores `"/bands"` once and only once.
const routeSet = new Set();

// Final HTML safety regex rules checked against every exported HTML file.
// `stripAssets: true` masks `https://assets.raggiesoft.com/...` URLs before testing
// prose rules so legacy CDN image filenames don't trigger false positives, while the
// first rule (`stripAssets: false`) scans 100% of the raw HTML including URLs.
const HTML_SAFETY_CHECKS = [
  { label: "Trauma-trigger surname block", regex: /\bouellette\b/i, stripAssets: false },
  { label: "Real-world VT landmark", regex: /\b(?:drillfield|torgersen|hokies?|burruss|lane\s+stadium|cassell\s+coliseum)\b/i, stripAssets: true },
  { label: "Progress Street house number", regex: /\b\d+\s+progress\s+street\b/i, stripAssets: true },
  { label: "Technical consumer-UI jargon", regex: /\b(?:HUMAN_VERIFIED|WebVTT|Inno\s+Setup|Zero-Database|Flat-File)\b/, stripAssets: true },
];

for (const file of htmlFiles) {
  // Convert an absolute file path like `/Users/.../out/bands/firelight.html` into
  // a relative forward-slash path like `"bands/firelight.html"` (replacing Windows
  // backslashes `\` just in case this script runs on Windows).
  const rel = path.relative(OUT_DIR, file).replace(/\\/g, "/");

  // Run safety check on every exported HTML document before allowing the build to pass
  const rawHtml = fs.readFileSync(file, "utf8");
  const assetCleanHtml = rawHtml.replace(
    /https:\/\/assets\.raggiesoft\.com\/[^\s"'<>]+/g,
    "https://assets.raggiesoft.com/_asset"
  );
  for (const rule of HTML_SAFETY_CHECKS) {
    const target = rule.stripAssets ? assetCleanHtml : rawHtml;
    const m = target.match(rule.regex);
    if (m) {
      console.error(`❌ [postbuild-seo] Safety violation (${rule.label}: "${m[0]}") in out/${rel}`);
      process.exit(1);
    }
  }

  // Exclude non-canonical error/internal templates from `sitemap.xml` so search
  // engines only index real content routes.
  if (
    rel === "404.html" ||
    rel === "404/index.html" ||
    rel.startsWith("_not-found")
  ) {
    continue;
  }

  // Map exported filenames back to clean web URL paths:
  // - `"index.html"`                -> `"/"`
  // - `"characters/katie/index.html"` -> `"/characters/katie"`
  // - `"characters/katie.html"`     -> `"/characters/katie"`
  let routePath = "/";
  if (rel === "index.html") {
    routePath = "/";
  } else if (rel.endsWith("/index.html")) {
    routePath = "/" + rel.slice(0, -"/index.html".length);
  } else {
    routePath = "/" + rel.slice(0, -".html".length);
  }
  routeSet.add(routePath);
}

// Convert the `Set` back into a sorted Array (`[...routeSet]`), placing the
// home page `"/"` first (`return -1`) and sorting all other paths alphabetically.
const sortedRoutes = [...routeSet].sort((a, b) => {
  if (a === "/") return -1;
  if (b === "/") return 1;
  return a.localeCompare(b);
});

/**
 * Assigns a relative crawl priority hint (`0.0` to `1.0`) for `sitemap.xml`:
 * - `"/"` (Home hub): `"1.0"`
 * - Top-level directories like `"/bands"` or `"/books"` (depth 1): `"0.9"`
 * - Individual detail guides like `"/bands/the-stardust-engine"` (depth 2+): `"0.8"`
 */
function priorityForRoute(routePath) {
  if (routePath === "/") return "1.0";
  const depth = routePath.split("/").filter(Boolean).length;
  return depth === 1 ? "0.9" : "0.8";
}

// Assemble the standard Sitemaps.org XML document using `.map()` to transform
// every route string into an indented `<url>...</url>` XML block.
const sitemapXml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...sortedRoutes.map((routePath) => {
    const loc = routePath === "/" ? `${ORIGIN}/` : `${ORIGIN}${routePath}`;
    return [
      "  <url>",
      `    <loc>${loc}</loc>`,
      `    <lastmod>${TODAY}</lastmod>`,
      "    <changefreq>weekly</changefreq>",
      `    <priority>${priorityForRoute(routePath)}</priority>`,
      "  </url>",
    ].join("\n");
  }),
  "</urlset>",
  "",
].join("\n");

// Write `sitemap.xml` to both `out/` (deployed immediately) and `public/` (available in `next dev`).
fs.writeFileSync(path.join(OUT_DIR, "sitemap.xml"), sitemapXml, "utf8");
fs.writeFileSync(path.join(PUBLIC_DIR, "sitemap.xml"), sitemapXml, "utf8");

console.log(
  `✅ [postbuild-seo] Generated sitemap.xml (${sortedRoutes.length} canonical routes), verified 404.html (noindex), IndexNow key, and HTML safety guard.`
);
